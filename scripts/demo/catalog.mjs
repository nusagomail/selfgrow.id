/** Slug dari judul: huruf kecil, angka & tanda hubung. */
export const slugify = (s) =>
  s
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");

/** Semua buku katalog, urut per kategori. */
export function catalogBooks() {
  const out = [];
  for (const [category, books] of Object.entries(CATALOG)) {
    books.forEach(([topic, title, subtitle], index) => {
      out.push({ category, topic, title, subtitle, slug: slugify(title), index });
    });
  }
  return out;
}
